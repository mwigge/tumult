//! The checked-in OTel-Arrow gRPC code (`src/otap/proto.rs`) must be exactly
//! what the generator emits for `arrow_service.proto`, and must keep the
//! generated clients out of production builds.

use std::path::{Path, PathBuf};

const MARKER: &str = "// This file is @generated by prost-build.\n";
const CLIENT_GATE: &str = r#"#[cfg(any(test, feature = "otap-client"))]"#;

fn checked_in() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("src/otap/proto.rs")
}

#[test]
fn generated_clients_are_not_part_of_production_builds() {
    let text = std::fs::read_to_string(checked_in()).unwrap();
    let lines: Vec<&str> = text.lines().collect();
    let clients: Vec<usize> = (0..lines.len())
        .filter(|&i| lines[i].starts_with("pub mod ") && lines[i].ends_with("_client {"))
        .collect();
    assert_eq!(clients.len(), 3, "traces, logs and metrics clients");
    for i in clients {
        assert_eq!(lines[i - 1], CLIENT_GATE, "above `{}`", lines[i]);
    }
}

/// Regenerates with `protoc` and compares. To accept a deliberate change:
/// `OTAP_PROTO_BLESS=1 cargo test -p tumult-ingest --test otap_proto_drift -- --ignored`.
#[test]
#[ignore = "needs protoc on PATH; CI runs it"]
fn checked_in_code_matches_the_proto() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let out = tempfile::TempDir::new().unwrap();
    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .client_mod_attribute(".", CLIENT_GATE)
        .emit_rerun_if_changed(false)
        .out_dir(out.path())
        .compile_protos(
            &[root.join("proto/opentelemetry/proto/experimental/arrow/v1/arrow_service.proto")],
            &[root.join("proto")],
        )
        .unwrap();
    let generated = std::fs::read_to_string(
        out.path()
            .join("opentelemetry.proto.experimental.arrow.v1.rs"),
    )
    .unwrap();
    let generated = generated
        .strip_prefix(MARKER)
        .expect("generator output starts with its marker line");

    let current = std::fs::read_to_string(checked_in()).unwrap();
    let (header, body) = current
        .split_once(MARKER)
        .expect("proto.rs keeps the generator's marker line");
    if std::env::var_os("OTAP_PROTO_BLESS").is_some() {
        std::fs::write(checked_in(), format!("{header}{MARKER}{generated}")).unwrap();
        return;
    }
    assert!(
        body == generated,
        "src/otap/proto.rs differs from what arrow_service.proto generates; \
         rerun this test with OTAP_PROTO_BLESS=1 and commit the result"
    );
}
