//! The HTML report of one run: what its journal holds, as one page that
//! needs nothing but itself.

mod charts;
mod context;
pub(in crate::commands) mod fmt;
pub(in crate::commands) mod measures;
mod steps;

use chrono::{DateTime, SecondsFormat, Utc};
use tumult_core::types::Journal;
use tumult_lake::RunVerdict;

use fmt::{badge, text};

#[cfg(test)]
pub(crate) use steps::step_row;

const STYLE: &str = include_str!("report.css");

/// The script that draws the charts: `ECharts` with what the report needs
/// of it. Built from `web/src/lib/report/main.ts` by `npm run build:report`.
const CHARTS: &str = include_str!("report-charts.js");

/// What a report says that its journal does not.
pub(crate) struct ReportFrame<'a> {
    /// The trace UI the trace of a step links to. No links without one.
    pub trace_ui_base: Option<&'a str>,
    /// The SHA-256 of the journal file.
    pub source_hash: &'a str,
    pub generated_at: DateTime<Utc>,
}

pub(crate) fn generate_html_report(journal: &Journal, frame: &ReportFrame<'_>) -> String {
    let title = text(&journal.experiment_title);
    let sections = [
        context::halt(journal),
        context::summary(journal),
        steps::steady_state(journal, frame.trace_ui_base),
        steps::steps(journal, frame.trace_ui_base),
        measures::objectives(journal),
        measures::load(journal),
        measures::measurements(journal),
        context::versions(journal),
        context::blast_radius(journal),
        context::estimate(journal),
        context::analysis(journal),
        context::regulatory(journal),
    ]
    .concat();
    format!(
        r#"<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Tumult report: {title}</title>
<style>
{STYLE}</style>
</head>
<body>
<main>
{header}{sections}{footer}</main>
{script}</body>
</html>
"#,
        header = header(journal, &title),
        footer = footer(frame),
        script = script(&sections),
    )
}

/// The script of the charts, for a report that has a chart. A report
/// without one is a page without a script.
fn script(sections: &str) -> String {
    if !sections.contains(charts::OPTION) {
        return String::new();
    }
    format!("<script>\n{CHARTS}\n</script>\n")
}

fn header(journal: &Journal, title: &str) -> String {
    // The badge has the tone of the verdict of the run, as on every page.
    let class = match tumult_lake::run_verdict(&journal.status.to_string()) {
        Some(RunVerdict::Pass) => "ok",
        Some(RunVerdict::Fail) => "fail",
        Some(RunVerdict::NoEvidence) | None => "muted",
    };
    format!(
        r#"<header>
<p class="eyebrow">Tumult run report</p>
<h1>{title}</h1>
<p class="lede">{status} Run <code>{id}</code></p>
{target}</header>
"#,
        status = badge(class, &journal.status.to_string()),
        id = text(&journal.experiment_id),
        target = target(journal),
    )
}

/// The target of the run as its definition declares it: the system, and
/// the environment when the definition names one. Nothing for a run
/// without a target.
fn target(journal: &Journal) -> String {
    let Some(target) = &journal.target else {
        return String::new();
    };
    let environment = target
        .environment
        .as_deref()
        .map_or_else(String::new, |e| format!(" in <code>{}</code>", text(e)));
    format!(
        "<p class=\"lede\">Target <code>{}</code>{environment}</p>\n",
        text(&target.system)
    )
}

fn footer(frame: &ReportFrame<'_>) -> String {
    format!(
        "<footer>
<p>Generated by <strong>Tumult</strong> v{version}, the Rust-native resilience intelligence platform<br>
Report generated: {generated}<br>
Source journal SHA-256: <code>{hash}</code></p>
</footer>
",
        version = env!("CARGO_PKG_VERSION"),
        generated = frame
            .generated_at
            .to_rfc3339_opts(SecondsFormat::Secs, true),
        hash = text(frame.source_hash),
    )
}
